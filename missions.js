export function parseFLLMissions(FIELD_W, FIELD_H) {
    const groupStack = [[1, 0, 0, 1, 0, 0]];
    const shapes = [];

    function mult(m1, m2) {
        return [
            m1[0] * m2[0] + m1[2] * m2[1],
            m1[1] * m2[0] + m1[3] * m2[1],
            m1[0] * m2[2] + m1[2] * m2[3],
            m1[1] * m2[2] + m1[3] * m2[3],
            m1[0] * m2[4] + m1[2] * m2[5] + m1[4],
            m1[1] * m2[4] + m1[3] * m2[5] + m1[5]
        ];
    }

    function apply(m, x, y) {
        return { x: m[0] * x + m[2] * y + m[4], y: m[1] * x + m[3] * y + m[5] };
    }

    function parseMatrix(str) {
        if(!str) return [1,0,0,1,0,0];
        const m = str.match(/matrix\(([^)]+)\)/);
        if(m) return m[1].split(',').map(Number);
        return [1,0,0,1,0,0];
    }

    const regex = /<g([^>]*)>|<\/g>|<rect([^>]+)style="([^"]+)"\/>|<ellipse([^>]+)style="([^"]+)"\/>/g;
    let match;
    while((match = regex.exec(svgRaw)) !== null) {
        const full = match[0];
        if (full.startsWith('<g')) {
            let mStr = null;
            const tMatch = match[1].match(/transform="([^"]+)"/);
            if (tMatch) mStr = tMatch[1];
            groupStack.push(mult(groupStack[groupStack.length-1], parseMatrix(mStr)));
        } else if (full.startsWith('</g>')) {
            groupStack.pop();
        } else if (full.startsWith('<rect')) {
            const m = groupStack[groupStack.length-1];
            const isBg = match[3].includes('rgb(16,16,16)');
            const x = Number(match[2].match(/x="([^"]+)"/)[1]);
            const y = Number(match[2].match(/y="([^"]+)"/)[1]);
            const w = Number(match[2].match(/width="([^"]+)"/)[1]);
            const h = Number(match[2].match(/height="([^"]+)"/)[1]);
            const p1 = apply(m, x, y), p2 = apply(m, x+w, y), p3 = apply(m, x+w, y+h), p4 = apply(m, x, y+h);
            shapes.push({ type: isBg ? 'bg' : 'poly', pts: [p1, p2, p3, p4] });
        } else if (full.startsWith('<ellipse')) {
            const m = groupStack[groupStack.length-1];
            const cx = Number(match[4].match(/cx="([^"]+)"/)[1]);
            const cy = Number(match[4].match(/cy="([^"]+)"/)[1]);
            const rx = Number(match[4].match(/rx="([^"]+)"/)[1]);
            const ry = Number(match[4].match(/ry="([^"]+)"/)[1]);
            const pts = [];
            for(let i=0; i<8; i++){
                const a = i * Math.PI / 4;
                pts.push(apply(m, cx + rx * Math.cos(a), cy + ry * Math.sin(a)));
            }
            shapes.push({ type: 'poly', pts });
        }
    }

    const bg = shapes.find(s => s.type === 'bg');
    if(!bg) return [];
    
    let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
    for(const p of bg.pts) {
        if(p.x < minX) minX = p.x;
        if(p.x > maxX) maxX = p.x;
        if(p.y < minY) minY = p.y;
        if(p.y > maxY) maxY = p.y;
    }

    const MAT_W = 2000;
    const MAT_H = 1143;
    const OFFSET_X = 181 - 200; // Shift left by 20cm (200mm)
    
    const scaleX = MAT_W / (maxX - minX);
    const scaleY = MAT_H / (maxY - minY);

    const missions = [];
    for(const s of shapes){
        if(s.type === 'poly') {
            const mPts = s.pts.map(p => ({
                x: OFFSET_X + (p.x - minX) * scaleX,
                y: MAT_H - (p.y - minY) * scaleY
            }));
            
            const mx = Math.min(...mPts.map(p=>p.x));
            const my = Math.min(...mPts.map(p=>p.y));
            const mw = Math.max(...mPts.map(p=>p.x)) - mx;
            const mh = Math.max(...mPts.map(p=>p.y)) - my;

            missions.push({
                pts: mPts,
                aabb: { x: mx, y: my, w: mw, h: mh, label: '' }
            });
        }
    }
    return missions;
}
